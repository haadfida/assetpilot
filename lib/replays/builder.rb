require "active_support/testing/time_helpers"

module Replays
  # Builds and verifies db/replays/*.json.
  #
  # Both run inside one transaction that is always rolled back: it reseeds (SeedData.run!, deterministic
  # ids), freezes the clock at AS_OF, and runs each scenario in its own savepoint with id sequences reset,
  # so mutating tools (check-in, scheduling) really execute but leave no trace. The database you run it
  # against is unchanged afterwards.
  #
  # verify re-executes every recorded tool_use input and requires the identical output, then rebuilds the
  # scenario and requires the identical fixture (ignoring timing, which includes measured tool durations).
  class Builder
    include ActiveSupport::Testing::TimeHelpers

    AS_OF = Time.utc(2026, 11, 5, 10, 0, 0)
    TIMING_KEYS = %w[t_ms duration_ms].freeze
    MUTABLE_TABLES = %w[checkouts maintenance_tasks].freeze

    def initialize(dir: Agent::Replays::DIR, scenarios: Scenarios::ALL)
      @dir = Pathname(dir)
      @scenarios = scenarios
    end

    def build_all
      sandbox { @scenarios.map { |sc| write(isolated { record(sc) }) } }
    end

    # Returns a list of problems (empty when every fixture checks out).
    def verify_all
      sandbox do
        @scenarios.flat_map do |sc|
          path = @dir.join("#{sc.slug}.json")
          next ["#{sc.slug}: missing #{path}"] unless path.exist?

          stored = JSON.parse(path.read)
          isolated { verify_tool_results(stored) } + isolated { verify_rebuild(sc, stored) }
        end
      end
    end

    def record(scenario)
      session = Session.new(scenario.prompt)
      scenario.script.call(session)
      {
        "slug" => scenario.slug,
        "prompt" => scenario.prompt,
        "aliases" => scenario.aliases,
        "recorded" => "synthetic",
        "note" => "Synthetic recording: the tool calls were executed for real against the seeded database " \
                  "(SeedData, clock frozen at as_of); the assistant text is composed from a template over " \
                  "those results by `rake replays:build`, not generated by a model. Timings are plausible " \
                  "estimates plus measured tool durations; token usage is estimated.",
        "model" => Agent::Config.current.model,
        "as_of" => AS_OF.iso8601,
        "status" => "succeeded",
        "stop_reason" => "end_turn",
        "iterations" => session.iterations,
        "duration_ms" => session.duration_ms,
        "usage" => session.usage,
        "steps" => session.steps
      }
    end

    private

    def write(fixture)
      @dir.mkpath
      @dir.join("#{fixture['slug']}.json").write("#{JSON.pretty_generate(fixture)}\n")
      fixture
    end

    def verify_tool_results(stored)
      results = stored["steps"].select { |st| st["type"] == "tool_result" }.index_by { |st| st["tool_use_id"] }
      stored["steps"].select { |st| st["type"] == "tool_use" }.filter_map do |use|
        unless (tool = Tools::Registry.fetch(use["name"]))
          next "#{stored['slug']}: unknown tool #{use['name']}"
        end
        problems = tool.schemer.validate(use["input"]).map { |e| e["error"] }
        next "#{stored['slug']}: #{use['id']} input fails the #{use['name']} schema: #{problems.join('; ')}" if problems.any?

        actual = Tools::Registry.call(use["name"], use["input"])
        expected = results.fetch(use["id"], {})["output"]
        "#{stored['slug']}: #{use['id']} #{use['name']} output differs from the recording" unless actual == expected
      end
    end

    def verify_rebuild(scenario, stored)
      rebuilt = record(scenario)
      return [] if strip_timing(rebuilt) == strip_timing(stored)

      ["#{scenario.slug}: fixture is stale; run `bin/rails replays:build`"]
    end

    def strip_timing(fixture)
      fixture.except("duration_ms").merge("steps" => fixture["steps"].map { |st| st.except(*TIMING_KEYS) })
    end

    def sandbox
      result = nil
      travel_to(AS_OF) do
        ActiveRecord::Base.transaction(requires_new: true) do
          SeedData.run!
          result = yield
          raise ActiveRecord::Rollback
        end
      end
      result
    end

    # One savepoint per scenario, with id sequences reset so records created by mutating tools get the
    # same ids on every build. (setval is not transactional, hence resetting before each scenario.)
    def isolated
      result = nil
      ActiveRecord::Base.transaction(requires_new: true) do
        conn = ActiveRecord::Base.connection
        MUTABLE_TABLES.each do |t|
          conn.execute("SELECT setval(pg_get_serial_sequence('#{t}', 'id'), COALESCE((SELECT MAX(id) FROM #{t}), 0) + 1, false)")
        end
        result = yield
        raise ActiveRecord::Rollback
      end
      result
    end
  end
end
